#!/usr/bin/env node
/*  Generates the Playbook's profile-tag library from the ENGINE, so the copy has one home.
    WHY BUILD-TIME AND NOT RUNTIME: playbook.html is 151KB and loads 15KB of JS. vv-core is
    373KB. Loading the whole engine into a documentation page to read one object would more
    than triple its payload for no reader-visible gain, so the markup is generated here and
    committed. The cost of that choice is that it CAN go stale, which is why --check exists
    and should run in the same place lint-inline does.
        node scripts/gen-tag-library.js          rewrite the block
        node scripts/gen-tag-library.js --check  exit 1 if the file is out of date
    Career-Stage is skipped: the arc above the library already documents those five.  */
const fs=require('fs'), path=require('path');
const ROOT=path.join(__dirname,'..');
global.window=global; const noop=()=>{};
global.document={createElement:()=>({style:{},classList:{add:noop,toggle:noop},setAttribute:noop,appendChild:noop}),
  head:{appendChild:noop,insertBefore:noop,firstChild:null},body:{classList:{add:noop}},
  getElementById:()=>null,querySelector:()=>null,querySelectorAll:()=>[],addEventListener:noop,
  getElementsByTagName:()=>[]};
global.matchMedia=()=>({matches:false,addEventListener:noop});
const V=require(path.join(ROOT,'vv-core.js'));
const esc=t=>String(t==null?'':t).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');

const groups=(V.FILTER_TAXONOMY.profile||[]).filter(g=>g.sub!=='Career-Stage');
const defs=V.TAG_DEFS; const missing=[];
let html='';
groups.forEach(g=>{
  html+='<div class="libgroup-h">'+esc(g.sub)+'</div><div class="taggrid">';
  (g.items||[]).forEach(it=>{
    const d=defs[it.v];
    if(!d){ missing.push(it.v); return; }
    html+='<div class="tagdef"><div class="tt"><span class="tn" data-tag="'+esc(it.v)+'">'+esc(it.v)+'</span>'
        + '<span class="pill">'+esc(g.sub)+'</span></div>'
        + '<div class="td">'+esc(d.oneLiner)+'</div>'
        + '<div class="drury">&quot;'+esc(d.def)+'&quot;</div>'
        + '<button class="more" onclick="toggleStory(event,this)">See more &#8250;</button></div>';
  });
  html+='</div>';
});
if(missing.length){ console.error('FAIL , taxonomy tags with no TAG_DEFS copy: '+missing.join(', ')); process.exit(2); }

const S='<!-- TAG-LIBRARY:START , generated by scripts/gen-tag-library.js , do not edit by hand -->';
const E='<!-- TAG-LIBRARY:END -->';
const file=path.join(ROOT,'playbook.html');
const src=fs.readFileSync(file,'utf8');
const i=src.indexOf(S), j=src.indexOf(E);
if(i<0||j<0){ console.error('FAIL , markers not found in playbook.html'); process.exit(2); }
const block=S+'\n'+html+'\n'+E;
const out=src.slice(0,i)+block+src.slice(j+E.length);
const tagCount=(html.match(/class="tagdef"/g)||[]).length;
if(process.argv.includes('--check')){
  if(out!==src){ console.error('FAIL , playbook.html tag library is STALE. Run: node scripts/gen-tag-library.js'); process.exit(1); }
  console.log('OK , tag library matches TAG_DEFS ('+tagCount+' tags, '+groups.length+' groups)'); process.exit(0);
}
fs.writeFileSync(file,out);
console.log('written , '+tagCount+' tags across '+groups.length+' groups');
